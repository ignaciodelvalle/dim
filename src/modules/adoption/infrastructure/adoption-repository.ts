// AdoptionRepository — thin Drizzle wrapper for adoption domain writes and reads.
// Accepts an optional `tx` parameter for use inside db.transaction() calls,
// mirroring the existing openCase(input, tx) pattern in the codebase.
// Returns domain types or lightweight shapes (not raw Drizzle row types).
// No auth logic — auth lives at the action / use-case edge.

import { and, eq, isNull, sql } from "drizzle-orm";

import {
  attachments,
  cases,
  db,
  organizations,
  ownerships,
  petEvents,
  pets,
  profiles,
  reminders,
} from "@/db";
import { closeCase, findOpenCaseForPetAndKind } from "@/lib/case-helpers";
import { validateEventPayload } from "@/lib/event-schemas";

// ---------------------------------------------------------------------------
// Type aliases
// ---------------------------------------------------------------------------

type Tx = Parameters<Parameters<typeof db.transaction>[0]>[0];
type PetRow = typeof pets.$inferSelect;
type FosterRow = { id: string; ownerUserId: string | null };
type SetEligibilityArgs = {
  petId: string;
  eligible: boolean;
  ineligibleReason: string | null;
  ineligibleReasonNotes: string | null;
  ineligibleUntil: Date | null;
  now: Date;
  userId: string;
  orgId: string;
  orgVerified: boolean;
  /** Previous eligibility state captured by the use-case BEFORE writing. */
  previousState: { eligible: boolean | null; reason: string | null } | null;
};

type SetListingStatusArgs = {
  petId: string;
  action: "publish" | "pause" | "unpause" | "unpublish";
  currentListedAt: Date | null;
  now: Date;
};

type UpdateListingContentArgs = {
  petId: string;
  story?: string | null;
  requirements?: string | null;
  ageBucket?: string | null;
  sizeEstimate?: string | null;
  energyLevel?: string | null;
  goodWithKids?: boolean | null;
  goodWithDogs?: boolean | null;
  goodWithCats?: boolean | null;
  needsYard?: boolean | null;
  feeArs?: number | null;
};

type InsertApplicationArgs = {
  petId: string;
  userId: string;
  orgId: string;
  housingType: string;
  otherPets: string | null;
  dailyRoutine: string | null;
  notes: string | null;
  motivation: string | null;
  priorPets: string | null;
  now: Date;
};

type ResolveApplicationArgs = {
  petId: string;
  applicationEventId: string;
  outcome: "approved" | "rejected" | "withdrawn";
  // For approved/rejected this is the shelter reviewer; for withdrawn it is the
  // applicant's own user id (they are the actor who resolved their application).
  reviewerUserId: string;
  orgId: string;
  orgVerified: boolean;
  reason?: string;
  autoGenerated?: boolean;
  notes: string | null;
  now: Date;
};

type InsertAdoptionFinalizedArgs = {
  petId: string;
  userId: string;
  orgId: string;
  orgVerified: boolean;
  custodyOwnershipId: string;
  adopterUserId: string;
  isStubAdopter: boolean;
  fosterRow: { id: string; ownerUserId: string | null } | null;
  fosterUserId: string | null;
  /** Pre-found custody case id, or null if not intaked. */
  custodyCaseId: string | null;
  displayName: string;
  phone: string | null;
  dni: string | null;
  contractAttachmentId: string | null;
  /** Supabase Storage path of the uploaded contract file (null when no file). */
  contractStoragePath: string | null;
  /** MIME type of the uploaded contract file (null when no file). */
  contractMimeType: string | null;
  /** Byte size of the stored (possibly re-encoded) contract file (null when no file). */
  contractFileSize: number | null;
  followupMonths: number | null;
  notes: string | null;
  /** Organization display name — used in reminder description copy. */
  orgDisplayName: string;
  /** Pet name — used in reminder description copy. */
  petName: string;
  now: Date;
};

type ShelterPetResult = (PetRow & { custodyOwnershipId: string }) | null;

type OrgRow = typeof organizations.$inferSelect;

type PetWithOrgResult = {
  pet: PetRow & { custodyOwnershipId: string };
  org: OrgRow;
} | null;

type ApplicationEventRow = typeof petEvents.$inferSelect;

